"""Bump the hand-maintained pins in pins.toml to their current upstream versions.

One policy per pin:

- `python.bundle` — newest stable CPython minor that satisfies the project's
  `requires-python` range.
- `toolchain.ubuntu_image` — advances only when the pinned LTS leaves standard
  support: the container's glibc is the packages' compatibility floor, so
  "newest LTS" would silently drop older target distros.
- `toolchain.nfpm` — latest GitHub release.
- `lang.*.whisper.revision` — the model repo's current snapshot commit.
- `lang.*.piper.revision` — the voice repo's newest tag.
- `stt.*.revision` — the speech model repo's current snapshot commit.
- `tts.*.model_revision` — the TTS model repo's current snapshot commit.
- `lang.*.version` — the language pack's own release version. Not fetched from
  upstream: its patch component is bumped whenever that pack's downloaded
  content (its `.files` checksums) changes, so the version always tracks the
  delivered models. Hand-edit it for a larger, semantic bump (e.g. a new voice).

The `lang.*.<model>.files` and `tts.*.files` checksum tables are regenerated
from the pinned revision on every run (large LFS weights read their sha256
from the Hugging Face tree listing, release assets from the GitHub release's
`digest` field, so this stays cheap; anything without an upstream digest is
hashed by download), so an in-place `voice`/`path` edit is reflected with no
extra step. The regenerated `tts.*` family is additionally written to
src/core/runtime_pins.toml — the packaged copy the runtime provisioner reads,
since pins.toml itself never ships.

Values are rewritten in place, so comments in pins.toml survive. Nothing is
committed; review with `git diff pins.toml`.
"""

import datetime as dt
import hashlib
import json
import os
import re
import subprocess
import urllib.request
from pathlib import Path

import tomllib
from packaging.specifiers import SpecifierSet
from packaging.version import Version

PINS = Path("pins.toml")
# Packaged copy of the generated TTS family, read by the runtime provisioner
# through importlib.resources (pins.toml is build-time-only).
RUNTIME_PINS = Path("src/core/runtime_pins.toml")
RUNTIME_HEADER = "# GENERATED by just update-pins — edit pins.toml\n\n"
# The model ships under a release name, not its source basename (model_path):
# config.py's KOKORO_MODEL stages it as kokoro-v1.0.onnx, and the `.files`
# table is keyed by that shipped name. The voices asset keeps its upstream
# name — `voices_asset` is both its source name and its shipped name.
KOKORO_MODEL_NAME = "kokoro-v1.0.onnx"


def fetch_json(url, token=None):
    """Return the JSON document at `url`."""
    request = urllib.request.Request(url)
    if token:
        request.add_header("Authorization", f"Bearer {token}")
    with urllib.request.urlopen(request) as response:
        return json.load(response)


def github_token():
    """Return a GitHub token from `GITHUB_TOKEN` or the gh CLI, else None."""
    if token := os.environ.get("GITHUB_TOKEN"):
        return token
    try:
        gh = subprocess.run(
            ["gh", "auth", "token"], capture_output=True, text=True, check=True
        )
    except (OSError, subprocess.CalledProcessError):
        return None
    return gh.stdout.strip() or None


def sha256_of(url):
    """Return the hex SHA-256 of the file at `url`."""
    digest = hashlib.sha256()
    with urllib.request.urlopen(url) as response:
        for chunk in iter(lambda: response.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def latest_python(requires_python):
    """Return the newest stable CPython cycle allowed by `requires_python`."""
    cycles = fetch_json("https://endoflife.date/api/python.json")
    allowed = SpecifierSet(requires_python)
    return max(
        (c["cycle"] for c in cycles if Version(c["cycle"]) in allowed),
        key=Version,
    )


def supported_ubuntu_image(current):
    """Advance the LTS base image only once the pinned one has gone EOL."""
    pinned = current.removeprefix("ubuntu:")
    today = dt.datetime.now(tz=dt.timezone.utc).date()
    supported = [
        c["cycle"]
        for c in fetch_json("https://endoflife.date/api/ubuntu.json")
        if c.get("lts") and dt.date.fromisoformat(c["eol"]) > today
    ]
    if pinned in supported:
        return current
    oldest = min(
        (c for c in supported if Version(c) > Version(pinned)),
        key=Version,
    )
    return f"ubuntu:{oldest}"


def latest_nfpm():
    """Return the newest nfpm release version."""
    release = fetch_json(
        "https://api.github.com/repos/goreleaser/nfpm/releases/latest",
        token=github_token(),
    )
    return release["tag_name"].removeprefix("v")


def release_asset_digest(repo, tag, asset):
    """Return the hex SHA-256 of a GitHub release asset, without downloading it.

    The API's `digest` field is the asset's own content hash. Some assets
    predate the field (this repo's voices-v1.1-zh.bin, at the time of writing),
    so those are hashed by download — the script's existing pattern for any
    file that carries no content hash upstream. An asset the release doesn't
    carry at all is a stale pin, refused the way `stt_files` refuses a partial
    model rather than surfacing as a download 404.
    """
    release = fetch_json(
        f"https://api.github.com/repos/{repo}/releases/tags/{tag}",
        token=github_token(),
    )
    for entry in release["assets"]:
        if entry["name"] != asset:
            continue
        if digest := entry.get("digest"):
            return digest.removeprefix("sha256:")
        return sha256_of(f"https://github.com/{repo}/releases/download/{tag}/{asset}")
    msg = f"{repo}@{tag} lacks release asset {asset!r}"
    raise SystemExit(msg)


def hf_revision(repo):
    """Return the current snapshot commit of the Hugging Face `repo`."""
    return fetch_json(f"https://huggingface.co/api/models/{repo}")["sha"]


def whisper_files(repo, revision):
    """Return `{filename: hex_sha256}` for the Whisper model files at `revision`.

    Mirrors stage-lang.sh's `*.bin`/`*.json`/`*.txt` selection. LFS weights
    already carry their sha256 in the tree listing; the smaller files are hashed
    by download, since their tree `oid` is a git SHA-1, not a content hash.
    """
    tree = fetch_json(
        f"https://huggingface.co/api/models/{repo}/tree/{revision}?recursive=true"
    )
    files = {}
    for entry in tree:
        path = entry["path"]
        if entry.get("type") != "file" or not path.endswith((".bin", ".json", ".txt")):
            continue
        if lfs := entry.get("lfs"):
            files[path] = lfs["oid"].removeprefix("sha256:")
        else:
            files[path] = sha256_of(
                f"https://huggingface.co/{repo}/resolve/{revision}/{path}"
            )
    return files


def piper_files(piper, revision):
    """Return `{filename: hex_sha256}` for the Piper voice's two files at `revision`.

    The `.onnx` weight is LFS, so its sha256 comes from the tree listing (no
    multi-MB download); the small `.onnx.json` is hashed by download. The listing
    is scoped to `path` because the voice repo holds every language's voices.
    """
    tree = fetch_json(
        f"https://huggingface.co/api/models/{piper['repo']}/tree/{revision}/{piper['path']}"
    )
    wanted = {f"{piper['voice']}.onnx", f"{piper['voice']}.onnx.json"}
    files = {}
    for entry in tree:
        name = entry["path"].rsplit("/", 1)[-1]
        if name not in wanted:
            continue
        if lfs := entry.get("lfs"):
            files[name] = lfs["oid"].removeprefix("sha256:")
        else:
            files[name] = sha256_of(
                f"https://huggingface.co/{piper['repo']}/resolve"
                f"/{revision}/{piper['path']}/{name}"
            )
    return files


def set_files(text, table, files):
    """Insert or replace the `[<table>.files]` table in `text`.

    `table` is a pack model's dotted table name, `lang.de.whisper` or
    `stt.parakeet`. The table is machine-owned, so it is rewritten wholesale
    rather than bumped key by key; a first run drops it in after the model's
    scalar keys, before the next table.
    """
    block = "\n".join(
        [f"[{table}.files]"] + [f'"{name}" = "{files[name]}"' for name in sorted(files)]
    )
    if match := re.search(rf"\[{re.escape(table)}\.files\]\n(?:\".*\n)*", text):
        return text[: match.start()] + block + "\n" + text[match.end() :]
    scalars = re.search(rf"\[{re.escape(table)}\]\n(?:[^\[\n].*\n)*", text)
    return text[: scalars.end()] + "\n" + block + "\n" + text[scalars.end() :]


def latest_piper_tag(repo):
    """Return the newest release tag of the Hugging Face `repo`."""
    refs = fetch_json(f"https://huggingface.co/api/models/{repo}/refs")
    return max(
        (tag["name"] for tag in refs["tags"]),
        key=lambda name: Version(name.removeprefix("v")),
    )


def bump(text, key, old, new, label):
    """Replace `key = "old"` in `text` with `new`, reporting the change."""
    if old == new:
        print(f"  ok    {label} = {old}")
        return text
    print(f"  bump  {label}: {old} -> {new}")
    return text.replace(f'{key} = "{old}"', f'{key} = "{new}"', 1)


def content(pack):
    """Return a pack's file→checksum map: its actual shipped content.

    A language pack's content is its Whisper and Piper files; a speech model
    pack's content is its own files. Empty until the `.files` tables have been
    generated, so a newly added pack (scalars only) reads as no content yet.
    """
    if "whisper" in pack:
        return {**pack["whisper"].get("files", {}), **pack["piper"].get("files", {})}
    return pack.get("files", {})


def next_patch(version):
    """Return `version` (X.Y.Z) with its patch component incremented."""
    major, minor, patch = version.split(".")
    return f"{major}.{minor}.{int(patch) + 1}"


def bump_pack_version(text, table, old, new):
    """Replace the `version` under the `[<table>]` header, reporting it.

    Anchored to the pack's own table header so packs that share a version number
    don't collide, unlike the section-agnostic `bump`.
    """
    print(f"  bump  {table}.version: {old} -> {new}")
    header = re.escape(f"[{table}]")
    return re.sub(
        rf'({header}\nversion = ")({re.escape(old)})(")',
        rf"\g<1>{new}\g<3>",
        text,
        count=1,
    )


def update_toolchain(text, pins, requires_python):
    """Bump the bundled CPython, build-container image, and nfpm pins in `text`."""
    text = bump(
        text,
        "bundle",
        pins["python"]["bundle"],
        latest_python(requires_python),
        "python.bundle",
    )
    text = bump(
        text,
        "ubuntu_image",
        pins["toolchain"]["ubuntu_image"],
        supported_ubuntu_image(pins["toolchain"]["ubuntu_image"]),
        "toolchain.ubuntu_image",
    )
    return bump(
        text, "nfpm", pins["toolchain"]["nfpm"], latest_nfpm(), "toolchain.nfpm"
    )


def update_language(text, code, lang):
    """Bump one language pack's Whisper and Piper revisions and refill its `.files`."""
    whisper, piper = lang["whisper"], lang["piper"]
    new_revision = hf_revision(whisper["repo"])
    text = bump(
        text,
        "revision",
        whisper["revision"],
        new_revision,
        f"lang.{code}.whisper.revision",
    )
    files = whisper_files(whisper["repo"], new_revision)
    text = set_files(text, f"lang.{code}.whisper", files)
    print(f"  files lang.{code}.whisper.files ({len(files)} files)")

    new_tag = latest_piper_tag(piper["repo"])
    text = bump(
        text, "revision", piper["revision"], new_tag, f"lang.{code}.piper.revision"
    )
    files = piper_files(piper, new_tag)
    text = set_files(text, f"lang.{code}.piper", files)
    print(f"  files lang.{code}.piper.files ({len(files)} files)")
    return text


def stt_files(stt, revision):
    """Return `{filename: hex_sha256}` for the speech model's files at `revision`.

    The files are the ones onnx-asr loads for the pinned quantization, named as
    the ONNX conversions name them; the weights are LFS, so their sha256 comes
    from the tree listing, and the small config and vocabulary are hashed by
    download.
    """
    suffix = f".{stt['quantization']}.onnx"
    wanted = {
        "config.json",
        "vocab.txt",
        f"encoder-model{suffix}",
        f"decoder_joint-model{suffix}",
    }
    tree = fetch_json(
        f"https://huggingface.co/api/models/{stt['repo']}/tree/{revision}"
    )
    files = {}
    for entry in tree:
        name = entry["path"]
        if name not in wanted:
            continue
        if lfs := entry.get("lfs"):
            files[name] = lfs["oid"].removeprefix("sha256:")
        else:
            files[name] = sha256_of(
                f"https://huggingface.co/{stt['repo']}/resolve/{revision}/{name}"
            )
    if missing := wanted - files.keys():
        msg = (
            f"{stt['repo']}@{revision} lacks {sorted(missing)}; "
            "not pinning a partial model"
        )
        raise SystemExit(msg)
    return files


def update_stt(text, code, stt):
    """Bump one speech model pack's revision and refill its `.files`."""
    new_revision = hf_revision(stt["repo"])
    text = bump(text, "revision", stt["revision"], new_revision, f"stt.{code}.revision")
    files = stt_files(stt, new_revision)
    text = set_files(text, f"stt.{code}", files)
    print(f"  files stt.{code}.files ({len(files)} files)")
    return text


def tts_files(tts, revision):
    """Return `{shipped_name: hex_sha256}` for the TTS engine's two files.

    Keys are the SHIPPED names (what config.py stages under KOKORO_DIR), not
    the source coordinates, because the provisioner stages and checksums under
    them. Unlike `piper_files`, whose listing is scoped to a directory, this
    one walks the whole tree: the exact `model_path` sits under `onnx/` in a
    repo whose root holds sibling formats, and the tree API 404s when handed a
    file path. Neither file needs to download for the pinned release: the
    model weight is LFS, so its sha256 comes from the tree listing, and the
    voices bin's from the release asset's `digest` field.
    """
    tree = fetch_json(
        f"https://huggingface.co/api/models/{tts['model_repo']}/tree/{revision}"
        "?recursive=true"
    )
    entry = next(
        (e for e in tree if e.get("type") == "file" and e["path"] == tts["model_path"]),
        None,
    )
    if entry is None or "lfs" not in entry:
        msg = (
            f"{tts['model_repo']}@{revision} lacks an LFS {tts['model_path']}; "
            "not pinning a partial model"
        )
        raise SystemExit(msg)
    files = {KOKORO_MODEL_NAME: entry["lfs"]["oid"].removeprefix("sha256:")}
    files[tts["voices_asset"]] = release_asset_digest(
        tts["voices_repo"], tts["voices_tag"], tts["voices_asset"]
    )
    return files


def update_tts(text, code, tts):
    """Bump one TTS engine pack's revision and refill its `.files`."""
    new_revision = hf_revision(tts["model_repo"])
    text = bump(
        text,
        "model_revision",
        tts["model_revision"],
        new_revision,
        f"tts.{code}.model_revision",
    )
    files = tts_files(tts, new_revision)
    text = set_files(text, f"tts.{code}", files)
    print(f"  files tts.{code}.files ({len(files)} files)")
    return text


def bump_versions(text, pins):
    """Bump each pack's version to follow its regenerated content.

    A pack's version tracks its models: where the refreshed `.files` checksums in
    `text` differ from what `pins` held, the patch component is bumped, so a
    changed model always ships under a new version. A newly added pack (no
    `.files` yet) keeps its hand-set version — the first checksum fill is not a
    change.
    """
    updated = tomllib.loads(text)
    for kind in ("lang", "stt", "tts"):
        for code, pack in pins.get(kind, {}).items():
            table = f"{kind}.{code}"
            was = content(pack)
            if was and was != content(updated[kind][code]):
                text = bump_pack_version(
                    text, table, pack["version"], next_patch(pack["version"])
                )
            else:
                print(f"  ok    {table}.version = {pack['version']}")
    return text


def runtime_copy(text):
    """Return the packaged `runtime_pins.toml` body: the generated TTS family.

    The provisioner is the pins' first runtime consumer, but pins.toml is
    build-time-only (MANIFEST.in prunes it; no package-data ships it), so the
    generated family ships as this packaged copy instead, read through
    importlib.resources. pins.toml stays the single hand-edited source of
    truth; this file is build output, exactly like the `.files` tables.
    """
    lines = []
    keep = False
    for line in text.splitlines(keepends=True):
        if line.startswith("["):
            keep = line.startswith("[tts.")
        if keep:
            lines.append(line)
    return RUNTIME_HEADER + "".join(lines)


def write_runtime_copy(text):
    """(Re)write the packaged runtime copy when the generated content moved."""
    body = runtime_copy(text)
    if RUNTIME_PINS.is_file() and RUNTIME_PINS.read_text(encoding="utf-8") == body:
        print(f"  ok    {RUNTIME_PINS}")
        return
    RUNTIME_PINS.write_text(body, encoding="utf-8")
    print(f"  wrote {RUNTIME_PINS}")


def main():
    """Refresh every pin and rewrite pins.toml when anything moved."""
    text = original = PINS.read_text(encoding="utf-8")
    pins = tomllib.loads(text)
    pyproject = tomllib.loads(Path("pyproject.toml").read_text(encoding="utf-8"))

    text = update_toolchain(text, pins, pyproject["project"]["requires-python"])
    for code, lang in pins["lang"].items():
        text = update_language(text, code, lang)
    for code, stt in pins.get("stt", {}).items():
        text = update_stt(text, code, stt)
    for code, tts in pins.get("tts", {}).items():
        text = update_tts(text, code, tts)
    text = bump_versions(text, pins)

    if text != original:
        PINS.write_text(text, encoding="utf-8")
    if pins.get("tts"):
        write_runtime_copy(text)


if __name__ == "__main__":
    main()
